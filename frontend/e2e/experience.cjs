// Fresh real API/SQLite required. Only delays and network faults are injected.
const { chromium } = require('playwright');
const fs = require('fs'), assert = require('assert');
(async () => {
  const url = process.env.AGENTSEC_E2E_URL;
  if (!url || !process.env.AGENTSEC_E2E_CREDENTIALS) throw Error('Provide fresh DB URL and credentials');
  const credentials = JSON.parse(fs.readFileSync(process.env.AGENTSEC_E2E_CREDENTIALS));
  const browser = await chromium.launch({headless:true, executablePath:process.env.AGENTSEC_E2E_CHROME});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage(), checks = [], errors = [];
  const pass = x => {checks.push(x); console.log('PASS: '+x);};
  page.setDefaultTimeout(15000);
  const login = async (p,u) => {await p.getByLabel('用户名',{exact:true}).fill(u.username); await p.getByLabel('密码',{exact:true}).fill(u.password); await p.getByRole('button',{name:'进入工作空间'}).click();};
  page.on('pageerror', x => errors.push(x.message));
  fs.mkdirSync('../test-results',{recursive:true});
  try {
    await page.route('**/api/auth/me', r => r.abort());
    await page.goto(url);
    await page.getByRole('heading',{name:'暂时无法连接工作空间'}).waitFor();
    assert.equal(await page.getByRole('heading',{name:'登录评测平台'}).count(),0);
    pass('bootstrap offline shows retry, not login');
    await page.unroute('**/api/auth/me');
    await page.getByRole('button',{name:'重试连接'}).click();
    await page.getByRole('heading',{name:'登录评测平台'}).waitFor();
    pass('bootstrap retry recovers');
    let release, reads=0;
    const gate = new Promise(resolve => {release=resolve;});
    await page.route('**/api/cases', async r => {reads++; await gate; await r.continue();});
    await login(page,credentials);
    await page.getByRole('heading',{name:'正在加载工作空间…'}).waitFor();
    assert.equal(await page.locator('.metric,.empty').count(),0);
    pass('initial loading does not invent empty or zero data');
    await page.waitForTimeout(4500); assert.equal(reads,1);
    pass('polling does not overlap unfinished load');
    release(); await page.getByText('平台已连接',{exact:true}).waitFor(); await page.unroute('**/api/cases');
    await page.getByRole('button',{name:'评测目标',exact:true}).click();
    await page.getByText('添加 fixture 可先体验完整流程；添加模型目标即可进行真实攻击评测。',{exact:true}).waitFor();
    assert.equal(await page.locator('.target-card').count(),0);
    pass('real empty DB displays useful empty state');
    await page.getByRole('button',{name:'添加目标',exact:true}).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('目标名称').fill('表单错误验收');
    await dialog.getByLabel('目标类型').selectOption('http-agent');
    await dialog.getByLabel('Agent API Endpoint').fill('http://unregistered.example/agent');
    const rejected=page.waitForResponse(r=>r.url().endsWith('/api/targets')&&r.request().method()==='POST');
    await dialog.getByRole('button',{name:'保存目标'}).click(); assert.equal((await rejected).status(),400);
    await dialog.getByRole('alert').waitFor(); await page.waitForTimeout(4500);
    assert.equal(await dialog.getByLabel('目标名称').inputValue(),'表单错误验收');
    assert.equal(await dialog.getByLabel('Agent API Endpoint').inputValue(),'http://unregistered.example/agent');
    assert(await dialog.getByRole('alert').isVisible());
    pass('real backend validation retains form and error through polling');
    await dialog.getByLabel('Agent API Endpoint').fill('http://127.0.0.1:9988/agent');
    await dialog.getByRole('button',{name:'保存目标'}).click(); await dialog.waitFor({state:'hidden'});
    await page.getByRole('heading',{name:'表单错误验收',exact:true}).waitFor();
    pass('corrected form saves to real API');
    await page.getByRole('button',{name:'添加目标',exact:true}).click();
    await dialog.getByLabel('目标名称').fill('断网后保留草稿');
    await context.setOffline(true); await dialog.getByRole('button',{name:'保存目标'}).click();
    await dialog.getByRole('alert').filter({hasText:'网络连接失败，请检查网络后重试'}).waitFor();
    await page.getByText('连接异常 · 显示上次数据',{exact:true}).waitFor();
    assert.equal(await page.locator('.target-card').count(),1);
    assert.equal(await dialog.getByLabel('目标名称').inputValue(),'断网后保留草稿');
    pass('offline write preserves draft and cached data with truthful status');
    await page.waitForTimeout(4500);
    assert.equal(await dialog.getByLabel('目标名称').inputValue(),'断网后保留草稿');
    pass('offline polling retains modal');
    await context.setOffline(false); // Existing modal remains open; background polling recovers.
    await page.getByText('平台已连接',{exact:true}).waitFor();
    assert(await dialog.getByRole('alert').isVisible());
    assert.equal(await dialog.getByLabel('目标名称').inputValue(),'断网后保留草稿');
    pass('recovered reads clear connection error and retain draft/form error');
    await dialog.getByRole('button',{name:'保存目标'}).click(); await dialog.waitFor({state:'hidden'});
    await page.getByRole('heading',{name:'断网后保留草稿',exact:true}).waitFor();
    pass('explicit write retry succeeds after restoration');
    await page.screenshot({path:'../test-results/experience-desktop.png',fullPage:true});
    const mobile=await browser.newContext({viewport:{width:390,height:844}}), mp=await mobile.newPage();
    mp.setDefaultTimeout(15000);
    mp.on('pageerror',x=>errors.push(x.message));
    await mp.goto(url); await mp.route('**/api/targets',r=>r.abort()); await login(mp,credentials.viewer);
    await mp.getByRole('heading',{name:'暂时无法加载工作空间'}).waitFor();
    assert.equal(await mp.locator('.empty').count(),0);
    await mp.getByText('连接异常 · 尚无数据',{exact:true}).waitFor({state:'attached'});
    assert(await mp.getByRole('alert').filter({hasText:'暂时无法加载工作空间'}).isVisible());
    pass('failed initial dataset load is distinct from empty state');
    await mp.unroute('**/api/targets'); await mp.getByRole('button',{name:'刷新',exact:true}).click();
    await mp.getByText('平台已连接',{exact:true}).waitFor({state:'attached'});
    assert.equal(await mp.locator('.metric').count(),4);
    await mp.getByRole('button',{name:'评测目标',exact:true}).click();
    assert.equal(await mp.getByRole('button',{name:'添加目标',exact:true}).count(),0);
    assert.equal(await mp.getByRole('button',{name:'开始评测',exact:true}).count(),0);
    pass('viewer sees no write controls');
    const csrf=(await mobile.cookies()).find(c=>c.name==='agentsec_csrf').value;
    const response=await mobile.request.post(url+'/api/targets',{headers:{'X-CSRF-Token':csrf,Origin:url},data:{name:'viewer mutation',kind:'fixture',config:{guard:'none'}}});
    assert.equal(response.status(),403); pass('real API rejects viewer mutation');
    assert(await mp.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mp.evaluate(()=>window.scrollTo(0,0));
    await mp.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
    await mp.screenshot({path:'../test-results/experience-mobile.png',fullPage:true});
    pass('mobile fits 390px viewport');
    assert.deepEqual(errors,[]);
    const result={passed:true,checks,consoleErrors:errors,evidence:'real fresh API/SQLite; delayed reads and browser offline fault injection'};
    fs.writeFileSync('../test-results/experience-result.json',JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2)); await mobile.close();
  } catch(x) {await page.screenshot({path:'../test-results/experience-failure.png',fullPage:true}).catch(()=>{}); throw x;} finally {await browser.close();}
})().catch(x=>{console.error(x);process.exit(1);});
