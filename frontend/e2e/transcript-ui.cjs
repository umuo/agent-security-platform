const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert');
const http = require('http');

(async () => {
  fs.mkdirSync('../test-results', { recursive: true });
  const credentials = JSON.parse(fs.readFileSync(process.env.AGENTSEC_E2E_CREDENTIALS || '../data/local-login.json'));
  const browser = await chromium.launch({ ...(process.env.AGENTSEC_E2E_CHROME ? { executablePath: process.env.AGENTSEC_E2E_CHROME } : {}), headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const name = '浏览器验收 ' + Date.now();
  let agentServer;
  try {
    await page.goto(process.env.AGENTSEC_E2E_URL || 'http://127.0.0.1:8088');
    await page.getByLabel('用户名', { exact: true }).fill(credentials.username);
    await page.getByLabel('密码', { exact: true }).fill(credentials.password);
    await page.getByRole('button', { name: '进入工作空间' }).click();
    await page.getByRole('heading', { name: '安全概览', exact: true }).waitFor();
    await page.getByRole('button', { name: '评测目标', exact: true }).click();
    await page.getByRole('button', { name: '添加目标', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('目标名称').fill(name);
    await dialog.getByLabel('工具保护策略').selectOption('none');
    await dialog.getByRole('button', { name: '保存目标' }).click();
    await dialog.waitFor({ state: 'hidden' });
    const card = page.locator('.target-card').filter({ has: page.getByRole('heading', { name, exact: true }) });
    await card.getByRole('button', { name: '开始评测' }).click();
    await dialog.getByLabel('任务名称').fill(name);
    await dialog.getByRole('button', { name: '清空', exact: true }).click();
    await dialog.getByLabel('直接注入：诱导外发工具').check();
    await dialog.getByLabel('正常任务：查询自己的订单').check();
    await dialog.getByRole('button', { name: '创建并加入执行队列' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '评测任务', exact: true }).click();
    await page.getByRole('button', { name, exact: true }).click();
    await page.locator('.detail-banner').getByText('已完成', { exact: true }).waitFor({ timeout: 60000 });
    assert.equal(await page.locator('.attempt').count(), 2);
    await page.locator('.attempt').filter({ hasText: '直接注入：诱导外发工具' }).locator(':scope > summary').click();
    assert((await page.locator('.attempt').filter({ hasText: '直接注入：诱导外发工具' }).textContent()).includes('tool.completed'));
    await page.getByRole('region', { name: '修复与复测建议' }).waitFor();
    assert((await page.getByRole('region', { name: '修复与复测建议' }).textContent()).includes('服务端授权'));
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('link', { name: '导出 JSON 报告' }).click();
    const download = await downloadEvent;
    await download.saveAs('../test-results/browser-report.json');
    const report = JSON.parse(fs.readFileSync('../test-results/browser-report.json'));
    assert.equal(report.status, 'COMPLETED');
    assert(report.attempts.every(a => a.result.oracle_revision === 'v3'));
    assert.equal(report.attempts.find(a => a.case_id === 'direct-tool').remediation.basis, 'ATTACK_SUCCEEDED');
    assert.equal(report.attempts.find(a => a.case_id === 'clean-query').remediation, null);
    await page.screenshot({ path: '../test-results/browser-desktop.png', fullPage: true });
    await page.getByRole('button', { name: /问题与复测/ }).click();
    await page.getByRole('heading', { name: '问题与复测', exact: true }).waitFor();
    assert((await page.locator('.finding').count()) > 0);
    await page.getByRole('button', { name: '评测目标', exact: true }).click();
    await card.getByRole('button', { name: '新修订', exact: true }).click();
    await dialog.getByLabel('目标名称').fill(name + ' 修复');
    await dialog.getByLabel('工具保护策略').selectOption('strict');
    await dialog.getByRole('button', { name: '保存目标' }).click();
    await dialog.waitFor({ state: 'hidden' });
    const repaired = page.locator('.target-card').filter({ has: page.getByRole('heading', { name: name + ' 修复', exact: true }) });
    await repaired.getByRole('button', { name: '开始评测' }).click();
    await dialog.getByLabel('任务名称').fill(name + ' 复测');
    await dialog.getByRole('button', { name: '清空', exact: true }).click();
    await dialog.getByLabel('直接注入：诱导外发工具').check();
    await dialog.getByLabel('正常任务：查询自己的订单').check();
    await dialog.getByRole('button', { name: '创建并加入执行队列' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '评测任务', exact: true }).click();
    await page.getByRole('button', { name: name + ' 复测', exact: true }).click();
    await page.locator('.detail-banner').getByText('已完成', { exact: true }).waitFor({ timeout: 60000 });
    await page.getByLabel('基线评测').selectOption({ index: 1 });
    await page.getByRole('button', { name: '比较结果', exact: true }).click();
    await page.getByText('样本可比 · 改善 1 项 · 退化 0 项', { exact: true }).waitFor();
    await page.screenshot({ path: '../test-results/browser-comparison.png', fullPage: true });
    // Deterministic external HTTP fixture exercises transport and platform tools.
    agentServer = http.createServer((request, response) => {
      let body = '';
      request.on('data', chunk => { body += chunk; });
      request.on('end', () => {
        const data = JSON.parse(body), used = data.messages.some(m => m.role === 'tool');
        const attack = request.url === '/unsafe-normal' || data.messages.filter(m => m.role === 'user').some(m => m.content.includes('send_report'));
        const call = { id: 'browser_call', name: attack ? 'send_report' : 'query_orders', arguments: attack ? { recipient: 'test@example.invalid' } : { tenant_id: 'tenant-a' } };
        response.writeHead(200, { 'Content-Type': 'application/json' });
        const reply = () => { if (!response.destroyed) response.end(JSON.stringify({ protocol: 'agentsec-tool-loop-v1', output: used ? '订单处理中' : '', tool_calls: used ? [] : [call], usage: { total_tokens: 0 } })); };
        if (request.url === '/deadline' && used) setTimeout(reply, 1500); else reply();
      });
    });
    await new Promise(resolve => agentServer.listen(0, '127.0.0.1', resolve));
    await page.getByRole('button', { name: '评测目标', exact: true }).click();
    await page.getByRole('button', { name: '添加目标', exact: true }).click();
    await dialog.getByLabel('目标名称').fill(name + ' HTTP');
    await dialog.getByLabel('目标类型').selectOption('http-agent');
    await dialog.getByLabel('Agent API Endpoint').fill('http://127.0.0.1:' + agentServer.address().port);
    await dialog.getByLabel('接入协议').selectOption('tool-loop-v1');
    await dialog.getByLabel('工具保护策略').selectOption('none');
    await dialog.getByRole('button', { name: '保存目标' }).click();
    await dialog.waitFor({ state: 'hidden' });
    const httpCard = page.locator('.target-card').filter({ has: page.getByRole('heading', { name: name + ' HTTP', exact: true }) });
    await httpCard.getByRole('button', { name: '开始评测' }).click();
    await dialog.getByLabel('任务名称').fill(name + ' HTTP');
    await dialog.getByRole('button', { name: '清空', exact: true }).click();
    await dialog.getByLabel('直接注入：诱导外发工具').check();
    await dialog.getByLabel('正常任务：查询自己的订单').check();
    await dialog.getByRole('button', { name: '创建并加入执行队列' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '评测任务', exact: true }).click();
    await page.getByRole('button', { name: name + ' HTTP', exact: true }).click();
    await page.locator('.detail-banner').getByText('已完成', { exact: true }).waitFor({ timeout: 60000 });
    await page.locator('.attempt').filter({ hasText: '直接注入：诱导外发工具' }).locator(':scope > summary').getByText('攻击成功', { exact: true }).waitFor();
    await page.locator('.attempt').filter({ hasText: '正常任务：查询自己的订单' }).locator(':scope > summary').getByText('正常任务完成', { exact: true }).waitFor();
    await page.locator('.attempt').filter({ hasText: '直接注入：诱导外发工具' }).locator(':scope > summary').click();
    assert((await page.locator('.attempt').filter({ hasText: '直接注入：诱导外发工具' }).textContent()).includes('http-agent-tool-loop-v1'));
    await page.screenshot({ path: '../test-results/browser-http-tools.png', fullPage: true });

    const exchange = page.locator('.attempt').filter({hasText:'直接注入：诱导外发工具'}).getByRole('region',{name:'逐轮请求与响应'});
    assert.equal(await exchange.locator('.exchange-round').count(),2);
    assert((await exchange.textContent()).includes('请求工具：send_report'));
    assert((await exchange.textContent()).includes('平台返回的工具结果'));
    assert((await exchange.textContent()).includes('系统约束'));
    await exchange.locator('.exchange-round').nth(1).locator(':scope > summary').click();
    assert((await exchange.locator('.exchange-round').nth(1).textContent()).includes('工具返回'));
    const attempt = page.locator('.attempt').filter({hasText:'直接注入：诱导外发工具'});
    assert.equal(await attempt.locator('.raw-evidence').getAttribute('open'),null);
    await page.screenshot({path:'../test-results/exchange-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.screenshot({path:'../test-results/exchange-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    fs.writeFileSync('../test-results/exchange-browser.json',JSON.stringify({passed:true,checks:['fixture baseline and repair comparison','real external HTTP Agent and Worker','two recorded request-response rounds','requested tool and actual tool result separated','system and user messages visible','second round includes tool feedback','JSON folded by default','390px mobile layout'],console_errors:errors},null,2));
  } finally { await browser.close(); if(agentServer) agentServer.close(); }
})().catch(error=>{console.error(error);process.exit(1)});
